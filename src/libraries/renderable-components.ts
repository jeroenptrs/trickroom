/** Whether the stage can render a registry component (false for unknown ids). */
export const hasStageRenderer = (library: string, component: string) =>
	Object.hasOwn(RENDERABLE_COMPONENT_IDS, library) &&
	RENDERABLE_COMPONENT_IDS[library as RegistryId].has(component);
